'use client';

import {Button, Card, Spin} from 'antd';
import {useRouter} from 'next/navigation';
import {useTranslations} from 'next-intl';
import React, {useEffect} from 'react';

import {ProtectedRoute} from '@/components/auth/ProtectedRoute';
import {MainLayout} from '@/components/layout/MainLayout';
import RoleForm from '@/components/roles/RoleForm';
import {PageHeader} from '@/components/ui/PageHeader';

import {useRoles} from '@/hooks/useRoles';

import {Status} from '@/types/common';


const RoleEditPage: React.FC<{ params: Promise<{ id: string }> }> = ({ params }) => {
  const resolvedParams = React.use(params);
  const router = useRouter();
  const { selectedRole, detailsStatus, getRoleById } = useRoles();
  const t = useTranslations();
  const entityName = t('role');

  useEffect(() => {
    const roleId = parseInt(resolvedParams.id);
    getRoleById(roleId);
  }, [resolvedParams.id, getRoleById]);


  if (detailsStatus.status === Status.LOADING) {
    return (
      <ProtectedRoute>
        <MainLayout>
          <div style={{ padding: '24px', textAlign: 'center' }}>
            <Spin />
            <div>{t('loading', { defaultValue: 'Loading...' })} {entityName}</div>
          </div>
        </MainLayout>
      </ProtectedRoute>
    );
  }

  if (!selectedRole || selectedRole.id !== parseInt(resolvedParams.id)) {
    return (
      <ProtectedRoute>
        <MainLayout>
          <div style={{ padding: '24px' }}>
            <Card>
              <div style={{ textAlign: 'center', padding: '50px' }}>
                <h2>{t('notFound_name', { name: entityName })}</h2>
                <Button type="primary" onClick={() => router.push('/roles')}>
                  {t('backToList_name', { name: entityName })}</Button>
              </div>
            </Card>
          </div>
        </MainLayout>
      </ProtectedRoute>
    );
  }

  return (
    <ProtectedRoute>
      <MainLayout>
          <PageHeader title={t('edit_name', { name: entityName })} onBack={() => router.back()} />
          <RoleForm
            mode="edit"
            roleId={parseInt(resolvedParams.id)}
            initialValues={selectedRole}
        />
      </MainLayout>
    </ProtectedRoute>
  );
};

export default RoleEditPage;
