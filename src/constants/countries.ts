// Helper function to get country by code
export const getCountryByCode = (code: string): ICountry | undefined => {
  return COUNTRIES.find((country) => country.code === code);
};

// Helper function to get country by name
export const getCountryByName = (name: string): ICountry | undefined => {
  return COUNTRIES.find((country) => country.name.toLowerCase() === name.toLowerCase());
};

// Helper function to search countries
export const searchCountries = (query: string): ICountry[] => {
  const lowercaseQuery = query.toLowerCase();
  return COUNTRIES.filter(
    (country) =>
      country.name.toLowerCase().includes(lowercaseQuery) ||
      country.code.toLowerCase().includes(lowercaseQuery),
  );
};
